// `bun web-apis.js`: writes src/strict/types/web-apis.d.ts, the Web APIs a strict app's JS has (globals.d.ts), as
// TypeScript's own lib.dom.d.ts declares them, with each type they name that a strict app has too. They're the WinterTC
// Minimum Common API's (https://min-common-api.proposal.wintertc.org), which a native host's sandbox has
// (clients/app/strict/src/js.rs) and a browser has, but the network's: no fetch, Request, Response, Headers or FormData.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

// What a strict app has, by its name in lib.dom.d.ts.
const offered = [
  "AbortController", "AbortSignal", "Blob", "ByteLengthQueuingStrategy", "CountQueuingStrategy", "Crypto", "CryptoKey",
  "CustomEvent", "DOMException", "ErrorEvent", "Event", "EventTarget", "File", "PromiseRejectionEvent",
  "ReadableByteStreamController", "ReadableStream", "ReadableStreamBYOBReader", "ReadableStreamBYOBRequest",
  "ReadableStreamDefaultController", "ReadableStreamDefaultReader", "SubtleCrypto", "TextDecoder", "TextDecoderStream",
  "TextEncoder", "TextEncoderStream", "TransformStream", "TransformStreamDefaultController", "URL", "URLSearchParams",
  "WritableStream", "WritableStreamDefaultController", "WritableStreamDefaultWriter",
  "atob", "btoa", "crypto", "reportError", "structuredClone",
]
// What a type it names may be that a strict app hasn't: only what can be transferred (`structuredClone`'s `transfer`)
// that it has.
const narrowed = { Transferable: "type Transferable = ArrayBuffer | ReadableStream | WritableStream | TransformStream;" }
// What a browser has of them that the sandbox doesn't, by the declaration it's in: the object URLs a page's elements
// load from, which nothing in a sandbox loads, and what the DOM keeps only for old pages.
const omitted = { URL: ["createObjectURL", "revokeObjectURL"], CustomEvent: ["initCustomEvent"], File: ["webkitRelativePath"] }

// TypeScript's libs, which are in its package for this machine (`typescript/lib/getExePath.js` finds it as this does).
const lib = join(dirname(fileURLToPath(import.meta.resolve(`@typescript/typescript-${process.platform}-${process.arch}/package.json`))), "lib")
const files = ["lib.dom.d.ts", "lib.dom.iterable.d.ts", "lib.dom.asynciterable.d.ts"].map((file) => readFileSync(join(lib, file), "utf8"))

// Each top-level declaration, with the comment before it, by the name it declares: a declaration that spans lines ends
// at the first line that starts with `}`.
const declared = new Map()
for (const text of files) {
  const lines = text.split("\n")
  let comment = []
  for (let at = 0; at < lines.length; at++) {
    const line = lines[at]
    if (line.startsWith("/**")) {
      comment = [line]
      while (!lines[at].includes("*/")) comment.push(lines[++at])
      continue
    }
    const name = line.match(/^(?:declare )?(?:interface|var|function|type|namespace) ([A-Za-z_$][\w$]*)/)?.[1]
    if (!name) {
      comment = []
      continue
    }
    const block = [...comment, line]
    if (line.trimEnd().endsWith("{")) {
      let member = []
      while (!lines[++at].startsWith("}")) {
        member.push(lines[at])
        if (lines[at].trimStart().startsWith("/**") || lines[at].trimStart().startsWith("*")) continue
        if (!omitted[name]?.includes(lines[at].match(/^\s+(?:readonly |static |new )?(\w+)/)?.[1])) block.push(...member)
        member = []
      }
      block.push(lines[at])
    }
    declared.set(name, [...(declared.get(name) ?? []), block.join("\n")])
    comment = []
  }
}

// What's offered, and each type that names that lib.dom.d.ts declares, until none is new: a type's name starts with a
// capital, where a property's, which may be a global's too (`name`, `self`), doesn't.
const kept = new Set()
const keep = (name) => {
  if (kept.has(name) || !declared.has(name)) return
  kept.add(name)
  if (narrowed[name]) return
  const text = declared.get(name).join("\n").replace(/\/\*\*[\s\S]*?\*\//g, "")
  for (const [named] of text.matchAll(/\b[A-Z][\w$]*\b/g)) if (named !== name) keep(named)
}
for (const name of offered) {
  if (!declared.has(name)) throw new Error(`lib.dom.d.ts declares no ${name}`)
  keep(name)
}

const version = JSON.parse(readFileSync(join(lib, "..", "package.json"), "utf8")).version
const header = `// Generated by core/ui/web-apis.js from TypeScript ${version}'s lib.dom.d.ts: don't change it by hand.
// Copyright (c) Microsoft Corporation. Licensed under the Apache License, Version 2.0.
`
writeFileSync(
  new URL("src/strict/types/web-apis.d.ts", import.meta.url),
  header + [...kept].sort().map((name) => narrowed[name] ?? declared.get(name).join("\n")).join("\n\n") + "\n",
)
console.log(`${kept.size} declarations: ${[...kept].sort().join(" ")}`)
